#!/usr/bin/env node
// Emit packages/substrate-config/toolchain.json: the fleet's toolchain versions,
// read from THIS repo's own configuration so there is one source, not a list
// someone retypes. `--check` exits 1 when the committed file is stale, which
// is what CI runs.
//
//   node scripts/emit-toolchain.mjs [--check]
//
// Consumers compare themselves against the published copy with the
// `substrate-toolchain-check` bin in @mnmal-ai/substrate-config.

import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(ROOT, 'packages/substrate-config/toolchain.json');

/** Toolchain packages a consumer is held to when it uses them. */
export const TRACKED = [
  '@biomejs/biome',
  '@modelcontextprotocol/sdk',
  '@types/node',
  'tsdown',
  'typescript',
  'vitest',
  'zod'
];

/** Top-level `catalog:` entries of a pnpm-workspace.yaml, unquoted. */
export function readCatalog(text) {
  const out = {};
  let on = false;
  for (const line of text.split('\n')) {
    if (/^catalog:\s*$/.test(line)) {
      on = true;
      continue;
    }
    if (!on) continue;
    if (line.trim() !== '' && !line.startsWith(' ')) break;
    const m = /^\s+["']?([^"':#]+?)["']?\s*:\s*["']?([^"'\s#]+)/.exec(line);
    if (m) out[m[1]] = m[2];
  }
  return out;
}

/** `uses: owner/action@<sha>  # vX.Y.Z` pins across workflow files; highest version wins. */
export function readActionPins(texts) {
  const pins = {};
  const num = (v) => v.replace(/^v/, '').split('.').map(Number);
  const newer = (a, b) => {
    const [x, y] = [num(a), num(b)];
    for (let i = 0; i < Math.max(x.length, y.length); i++)
      if ((x[i] ?? 0) !== (y[i] ?? 0)) return (x[i] ?? 0) > (y[i] ?? 0);
    return false;
  };
  for (const text of texts) {
    for (const m of text.matchAll(/uses:\s*([\w./-]+)@([0-9a-f]{40})\s*#\s*(v[\d.]+)/g)) {
      const [, action, sha, version] = m;
      if (pins[action] === undefined || newer(version, pins[action].version))
        pins[action] = { sha, version };
    }
  }
  return Object.fromEntries(Object.entries(pins).sort(([a], [b]) => a.localeCompare(b)));
}

export function buildManifest(root) {
  const pkg = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'));
  const catalog = readCatalog(readFileSync(join(root, 'pnpm-workspace.yaml'), 'utf8'));
  const biome = JSON.parse(readFileSync(join(root, 'biome.json'), 'utf8'));
  const wf = join(root, '.github/workflows');
  const workflows = readdirSync(wf)
    .filter((f) => /\.ya?ml$/.test(f))
    .map((f) => readFileSync(join(wf, f), 'utf8'));
  return {
    $comment:
      'Generated by scripts/emit-toolchain.mjs in mnmal-ai/substrate from its own config. Do not edit; compare with `substrate-toolchain-check`.',
    node: { engines: pkg.engines?.node },
    pnpm: String(pkg.packageManager ?? '').replace(/^pnpm@/, ''),
    biomeSchema: /schemas\/([\d.]+)\//.exec(biome.$schema ?? '')?.[1],
    catalog: Object.fromEntries(
      TRACKED.filter((k) => catalog[k] !== undefined).map((k) => [k, catalog[k]])
    ),
    actions: readActionPins(workflows)
  };
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const next = `${JSON.stringify(buildManifest(ROOT), null, 2)}\n`;
  if (process.argv.includes('--check')) {
    // The Renovate presets name the same toolchain; a second list nothing
    // checks is how these drift. TRACKED plus the two runtimes, exactly.
    const want = [...TRACKED, 'node', 'pnpm'].sort();
    for (const preset of ['fleet-lead', 'fleet-follower']) {
      const cfg = JSON.parse(readFileSync(join(ROOT, `renovate-presets/${preset}.json`), 'utf8'));
      const rule = cfg.packageRules.find((r) => (r.matchPackageNames ?? []).includes('vitest'));
      const have = [...(rule?.matchPackageNames ?? [])].sort();
      if (JSON.stringify(have) !== JSON.stringify(want)) {
        console.error(
          `renovate-presets/${preset}.json toolchain list differs from TRACKED: ${JSON.stringify(have)} vs ${JSON.stringify(want)}`
        );
        process.exit(1);
      }
    }
    let current = '';
    try {
      current = readFileSync(OUT, 'utf8');
    } catch {}
    if (current !== next) {
      console.error('toolchain.json is stale: run `node scripts/emit-toolchain.mjs` and commit it');
      process.exit(1);
    }
    console.log('toolchain.json is current');
  } else {
    writeFileSync(OUT, next);
    console.log(`wrote ${OUT}`);
  }
}
