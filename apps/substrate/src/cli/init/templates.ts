import { join } from 'node:path';
import type { EmbedderMode } from './config.js';
import { pluginNpmName, pluginRange } from './plugins.js';

export interface TemplateContext {
  readonly store: 'memory' | 'postgres';
  readonly port: number;
  readonly pgPort: number;
  readonly plugins: readonly string[];
  readonly embedder: EmbedderMode;
  /** Public URL clients use to reach this instance (rendered into the README; not a server env var). */
  readonly substrateUrl: string;
  readonly tls: boolean;
  readonly tlsCertPath: string | undefined;
  readonly tlsKeyPath: string | undefined;
  readonly pgPassword: string;
  readonly dbName: string;
  readonly composeName: string;
  readonly substrateVersion: string;
}

export function envBinaryTemplate(ctx: TemplateContext): string {
  const lines: string[] = [
    '# Substrate runtime — environment config.',
    '# Generated by `substrate init`. Edit values, then `substrate serve` (or wrap in systemd).',
    ''
  ];

  if (ctx.store === 'postgres') {
    lines.push(
      `SUBSTRATE_DATABASE_URL=postgres://substrate:${ctx.pgPassword}@127.0.0.1:${ctx.pgPort}/${ctx.dbName}`
    );
  } else {
    lines.push('SUBSTRATE_DATABASE_URL=memory');
  }
  lines.push('');

  lines.push('# Plugin install root — manifest-driven loader scans node_modules under this dir.');
  lines.push('SUBSTRATE_PLUGIN_DIR=.');
  lines.push('');

  lines.push(`PORT=${ctx.port}`);
  lines.push('');

  // A scaffolded runtime ships with auth OFF, and `compose` refuses to boot in
  // that state without an actor, so the scaffold supplies one.
  lines.push('# Who this deployment writes as while auth is off. Every row it writes');
  lines.push('# carries this in createdBy. Turn auth on and callers are attributed');
  lines.push('# individually instead, at which point this is ignored.');
  lines.push('SUBSTRATE_SYSTEM_ACTOR=local-dev');
  lines.push('');

  if (ctx.tls) {
    lines.push('# TLS termination — paths to existing cert + key on disk.');
    lines.push(`SUBSTRATE_TLS_CERT_PATH=${ctx.tlsCertPath ?? ''}`);
    lines.push(`SUBSTRATE_TLS_KEY_PATH=${ctx.tlsKeyPath ?? ''}`);
    lines.push('');
  }

  // Trim trailing blank line for a tidy file.
  while (lines.length > 0 && lines[lines.length - 1] === '') lines.pop();
  return `${lines.join('\n')}\n`;
}

/**
 * The in-process models, run by fastembed. Each name is a key of
 * `OnnxEmbedder`'s model map, and the dimension is the model's own.
 */
const ONNX_MODELS = {
  minilm: { model: 'all-MiniLM-L6-v2', dimension: 384 },
  'bge-base': { model: 'bge-base-en-v1.5', dimension: 768 }
} as const;

/** The onnx embedder's backend. Undeclared by substrate-embedder, so the runtime installs it. */
export const FASTEMBED_RANGE = '^2.1.1';

/**
 * `<runtime>/substrate-recall.config.json`, or null for `--embedder=none`. The
 * recall plugin reads its embedder from this file (merged by the manifest
 * loader), not from env.
 *
 * `cacheDir` is absolute because fastembed's own default is `local_cache`
 * under the working directory, which moves with whoever starts the server.
 */
export function recallConfigTemplate(embedder: EmbedderMode, runtimeDir: string): string | null {
  if (embedder === 'none') return null;
  const config =
    embedder === 'ollama'
      ? {
          embedder: {
            kind: 'ollama',
            baseUrl: 'http://localhost:11434',
            model: 'hf.co/CompendiumLabs/bge-base-en-v1.5-gguf:F16',
            dimension: 768
          }
        }
      : {
          embedder: {
            kind: 'onnx',
            ...ONNX_MODELS[embedder],
            cacheDir: join(runtimeDir, 'models')
          }
        };
  return `${JSON.stringify(config, null, 2)}\n`;
}

export function envDockerTemplate(ctx: TemplateContext): string {
  if (ctx.store === 'memory') return '';
  return [
    '# Postgres compose config — consumed by docker-compose.yml.',
    `POSTGRES_PASSWORD=${ctx.pgPassword}`,
    'POSTGRES_USER=substrate',
    `SUBSTRATE_DATABASE_NAME=${ctx.dbName}`,
    ''
  ].join('\n');
}

export function dockerComposeTemplate(ctx: TemplateContext): string {
  if (ctx.store === 'memory') return '';
  return `# Generated by \`substrate init\`. Postgres + backup sidecar.
name: ${ctx.composeName}

services:
  postgres:
    image: pgvector/pgvector:pg17
    restart: unless-stopped
    environment:
      POSTGRES_USER: \${POSTGRES_USER:-substrate}
      POSTGRES_PASSWORD: \${POSTGRES_PASSWORD:?POSTGRES_PASSWORD must be set in .env.docker, so pass --env-file .env.docker}
      POSTGRES_DB: \${SUBSTRATE_DATABASE_NAME:-${ctx.dbName}}
    ports:
      - "127.0.0.1:${ctx.pgPort}:5432"
    volumes:
      - ./data/pg:/var/lib/postgresql/data
      - ./postgres-init:/docker-entrypoint-initdb.d:ro
    healthcheck:
      test: ["CMD-SHELL", "pg_isready -U \${POSTGRES_USER:-substrate} -d \${SUBSTRATE_DATABASE_NAME:-${ctx.dbName}}"]
      interval: 10s
      timeout: 5s
      retries: 6
      start_period: 30s

  # Backup sidecar — COMMENTED OUT: no backups run until you opt
  # in. pg_dump on a loop (every 24h, retain 14 days — tunable via
  # BACKUP_INTERVAL_HOURS / BACKUP_RETENTION_DAYS). To enable:
  #   1. mkdir backups && touch backups/.substrate-backup-target (the marker the
  #      loop requires — without it the loop refuses to write),
  #   2. uncomment the block below and run docker compose --env-file .env.docker up -d again.
  # Each dump is a gzipped plain SQL file: restore with gunzip -c <file> | psql.
  #
  #  postgres-backup:
  #    image: pgvector/pgvector:pg17
  #    restart: unless-stopped
  #    depends_on:
  #      postgres:
  #        condition: service_healthy
  #    user: "\${HOST_UID:-1000}:\${HOST_GID:-1000}"
  #    environment:
  #      PGHOST: postgres
  #      PGUSER: \${POSTGRES_USER:-substrate}
  #      PGPASSWORD: \${POSTGRES_PASSWORD:?POSTGRES_PASSWORD must be set in .env.docker}
  #      PGDATABASE: \${SUBSTRATE_DATABASE_NAME:-${ctx.dbName}}
  #      BACKUP_INTERVAL_HOURS: \${BACKUP_INTERVAL_HOURS:-24}
  #      BACKUP_RETENTION_DAYS: \${BACKUP_RETENTION_DAYS:-14}
  #    volumes:
  #      - ./backups:/backups
  #    entrypoint: ["/bin/sh", "-c"]
  #    command:
  #      - |
  #        [ -f /backups/.substrate-backup-target ] || { echo "backups/.substrate-backup-target missing, refusing to write" >&2; exit 1; }
  #        while :; do
  #          out=/backups/$$PGDATABASE-$$(date -u +%Y%m%dT%H%M%SZ).sql.gz
  #          if pg_dump -Z 6 -f "$$out.partial"; then mv "$$out.partial" "$$out"; echo "backup ok $$out"
  #          else rm -f "$$out.partial"; echo "backup FAILED" >&2; fi
  #          find /backups -maxdepth 1 -name '*.sql.gz' -mtime +$$BACKUP_RETENTION_DAYS -delete
  #          sleep $$((BACKUP_INTERVAL_HOURS * 3600))
  #        done
`;
}

export function runtimePackageJsonTemplate(ctx: TemplateContext): string {
  // A prerelease satisfies no `^<major>.0.0`, so a prerelease binary ranges from its own version.
  const range = ctx.substrateVersion.includes('-')
    ? `^${ctx.substrateVersion}`
    : `^${ctx.substrateVersion.split('.')[0]}.0.0`;
  const deps: Record<string, string> = { '@mnmal-ai/substrate': range };
  for (const p of ctx.plugins) deps[pluginNpmName(p)] = pluginRange(p, range);
  if (ctx.embedder === 'minilm' || ctx.embedder === 'bge-base') deps.fastembed = FASTEMBED_RANGE;
  return `${JSON.stringify({ name: 'substrate-runtime', private: true, dependencies: deps }, null, 2)}\n`;
}

/**
 * pnpm 11 fails the install outright on a dependency build script nobody has
 * approved. These two ship prebuilt binaries and their scripts only fetch
 * extras, but an unanswered script is an error, not a skip.
 */
export function pnpmWorkspaceTemplate(): string {
  return [
    'packages: []',
    'allowBuilds:',
    '  msgpackr-extract: true',
    '  onnxruntime-node: true',
    ''
  ].join('\n');
}

export function pgInitSqlTemplate(ctx: TemplateContext): string {
  if (ctx.store === 'memory') return '';
  return `-- Idempotent create of the application database.
SELECT 'CREATE DATABASE ${ctx.dbName} OWNER substrate'
WHERE NOT EXISTS (SELECT FROM pg_database WHERE datname = '${ctx.dbName}')
\\gexec
`;
}

export function readmeTemplate(ctx: TemplateContext): string {
  const lines: string[] = [
    '# Substrate runtime',
    '',
    'Generated by `substrate init`.',
    '',
    '## Quickstart',
    ''
  ];
  if (ctx.store === 'postgres') {
    lines.push('```bash');
    lines.push('# 1. Start postgres.');
    lines.push('docker compose --env-file .env.docker up -d');
    lines.push('');
    lines.push('# 2. Install substrate binary + plugins.');
    lines.push('pnpm install');
    lines.push('');
    lines.push('# 3. Run substrate.');
    lines.push('set -a && source .env && set +a && ./node_modules/.bin/substrate serve');
    lines.push('```');
  } else {
    lines.push('```bash');
    lines.push('# Memory mode — data vanishes on restart.');
    lines.push('pnpm install');
    lines.push('set -a && source .env && set +a && ./node_modules/.bin/substrate serve');
    lines.push('```');
  }
  // Backups only mean something on postgres: memory mode keeps no durable
  // state to dump.
  if (ctx.store === 'postgres') {
    lines.push('');
    lines.push('## Backups');
    lines.push('');
    lines.push(
      'None are configured. The scaffolded `docker-compose.yml` runs postgres only — ' +
        'the `postgres-backup` sidecar is present but commented out, so this instance ' +
        'has no backup story until you opt in. Uncomment it per the comments in the ' +
        'compose file.'
    );
  }
  if (ctx.embedder !== 'none') {
    lines.push('');
    lines.push('## Semantic recall');
    lines.push('');
    lines.push(...recallReadmeLines(ctx.embedder));
  }
  lines.push('');
  lines.push('## Reaching this instance');
  lines.push('');
  const curlFlags = ctx.substrateUrl.startsWith('https') ? '-sfk' : '-sf';
  lines.push(`Health check: \`curl ${curlFlags} ${ctx.substrateUrl}/health\``);
  lines.push('');
  lines.push(
    `Clients (MCP/CLI — e.g. \`.mcp.json\`) connect via \`SUBSTRATE_URL=${ctx.substrateUrl}\`. ` +
      `That's a **client** setting: the server reads \`PORT\`${ctx.tls ? ' + the TLS paths' : ''}, not \`SUBSTRATE_URL\`.`
  );
  return `${lines.join('\n')}\n`;
}

function recallReadmeLines(embedder: Exclude<EmbedderMode, 'none'>): string[] {
  const lines =
    embedder === 'ollama'
      ? [
          '`substrate-recall.config.json` points at Ollama on `localhost:11434` with bge-base-en-v1.5. ' +
            'Pull the model first: `ollama pull hf.co/CompendiumLabs/bge-base-en-v1.5-gguf:F16`.'
        ]
      : [
          `\`substrate-recall.config.json\` runs \`${ONNX_MODELS[embedder].model}\` in-process ` +
            'through `fastembed`, which `pnpm install` adds (about 540MB, most of it ONNX Runtime). ' +
            'The first write downloads the model into `models/`.'
        ];
  lines.push(
    '',
    'Recall also ranks by keyword, so a small model loses little. Changing model later means ' +
      'emptying the stored vectors and embedding every row again, through the admin route ' +
      '`POST /substrate/v1/embed/reindex`.'
  );
  return lines;
}
